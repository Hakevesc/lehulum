/* Receipt → PDF. Reads what the receipt screen shows (title, every .detail-row label/value,
   the amount, the QR) and saves an A5 PDF named after the transaction ID.
   Usage: ReceiptPDF.download({ root: '.receipt-card', name: 'M-PESA Savings' }). Needs jsPDF (loaded on demand). */
(function () {
  const JSPDF = 'https://cdnjs.cloudflare.com/ajax/libs/jspdf/2.5.1/jspdf.umd.min.js';
  function loadLib() {
    if (window.jspdf) return Promise.resolve();
    return new Promise((ok, no) => { const s = document.createElement('script'); s.src = JSPDF; s.onload = ok; s.onerror = no; document.head.appendChild(s); });
  }
  const clean = t => (t || '').replace(/\s+/g, ' ').replace(/Copy ID|Copied!/g, '').trim();
  function imgData(img) {
    try {
      if (!img || !img.complete || !img.naturalWidth) return null;
      if (/^data:image\/(png|jpe?g)/.test(img.src)) return img.src;
      const c = document.createElement('canvas'); c.width = img.naturalWidth; c.height = img.naturalHeight;
      c.getContext('2d').drawImage(img, 0, 0); return c.toDataURL('image/png');
    } catch (e) { return null; }
  }

  async function download({ root = '.receipt-card', name = 'M-PESA', toast } = {}) {
    const say = m => { if (toast) toast(m); };
    say('Preparing PDF…');
    try { await loadLib(); } catch (e) { say('Could not load the PDF tool. Check your connection.'); return; }
    const box = document.querySelector(root) || document.body;
    const title = clean((box.querySelector('h2') || {}).textContent) || 'Transaction Receipt';
    const rows = [...box.querySelectorAll('.detail-row')].map(r => [clean((r.querySelector('.label') || {}).textContent), clean((r.querySelector('.value') || {}).textContent)])
      .filter(([k, v]) => k && v && v !== '—');
    const amtEl = box.querySelector('.amount-value'), amtSec = box.querySelector('.amount-section');
    const amount = amtEl && amtSec && getComputedStyle(amtSec).display !== 'none' && clean(amtEl.textContent) ? clean(amtEl.textContent) + ' ETB' : '';
    const who = clean((box.querySelector('.beneficiary-name') || {}).textContent);
    const txId = (rows.find(([k]) => /transaction id/i.test(k)) || [])[1] || String(Date.now());

    const { jsPDF } = window.jspdf, doc = new jsPDF({ unit: 'pt', format: 'a5' });
    const W = doc.internal.pageSize.getWidth(), M = 32, RED = [254, 53, 61], INK = [28, 28, 33], LOW = [124, 124, 135];
    // Header band
    doc.setFillColor(...RED); doc.rect(0, 0, W, 64, 'F');
    doc.setTextColor(255, 255, 255); doc.setFont('helvetica', 'bold'); doc.setFontSize(16); doc.text('M-PESA', M, 30);
    doc.setFont('helvetica', 'normal'); doc.setFontSize(9.5); doc.text(name, M, 46);
    doc.setFontSize(9); doc.text(new Date().toLocaleString('en-GB'), W - M, 30, { align: 'right' });
    // Title
    let y = 96;
    doc.setTextColor(...INK); doc.setFont('helvetica', 'bold'); doc.setFontSize(14);
    doc.text(doc.splitTextToSize(title, W - M * 2), W / 2, y, { align: 'center' }); y += 14;
    doc.setFont('helvetica', 'normal'); doc.setFontSize(9); doc.setTextColor(...LOW);
    doc.text('Thank you for choosing M-PESA Lehulum', W / 2, y + 4, { align: 'center' }); y += 26;
    // Rows
    doc.setFontSize(10);
    rows.forEach(([k, v], i) => {
      const lines = doc.splitTextToSize(v, (W - M * 2) * 0.55);
      doc.setTextColor(...LOW); doc.setFont('helvetica', 'normal'); doc.text(k, M, y);
      doc.setTextColor(...INK); doc.setFont('helvetica', 'bold'); doc.text(lines, W - M, y, { align: 'right' });
      y += 12 * lines.length + 6;
      if (i < rows.length - 1) { doc.setDrawColor(236, 236, 239); doc.line(M, y - 4, W - M, y - 4); y += 6; }
    });
    // Amount + QR
    if (amount) {
      y += 14;
      if (who) { doc.setFont('helvetica', 'normal'); doc.setFontSize(10); doc.setTextColor(...LOW); doc.text(who, W / 2, y, { align: 'center' }); y += 18; }
      doc.setFont('helvetica', 'bold'); doc.setFontSize(20);
      doc.setTextColor(...(amount.startsWith('-') ? RED : [22, 163, 74])); doc.text(amount, W / 2, y, { align: 'center' }); y += 12;
      const qr = imgData(box.querySelector('.qr-wrapper img'));
      if (qr) { const s = 96; doc.addImage(qr, 'PNG', (W - s) / 2, y + 6, s, s); y += s + 12; }
    }
    // Footer
    const H = doc.internal.pageSize.getHeight();
    doc.setFont('helvetica', 'normal'); doc.setFontSize(8); doc.setTextColor(...LOW);
    doc.text('This receipt was generated by the M-PESA app. Keep it for your records.', W / 2, H - 22, { align: 'center' });
    doc.save(`M-PESA-${txId.replace(/[^\w-]/g, '')}.pdf`);
    say('Receipt downloaded as PDF');
  }
  window.ReceiptPDF = { download };
})();
